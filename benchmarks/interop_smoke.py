"""Interop smoke test — drive PRAGMA through a tool-generated OpenAPI client (paper §6.2, P4).

The client under test is NOT hand-written: it was generated by
`openapi-python-client` (v0.29.1) from the *published* /openapi.json, i.e. a
third-party toolchain that knows nothing about our implementation. Passing this
end-to-end flow proves the contract is machine-usable by any conformant client.

Run against a live server:  uv run python benchmarks/interop_smoke.py
"""

from __future__ import annotations

import sys
from pathlib import Path

# the generated client lives outside the repo (generated artifact, not committed)
_GEN = Path("/tmp/interop_client/client")
sys.path.insert(0, str(_GEN))

from pragma_intent_management_api_client.client import Client  # noqa: E402
from pragma_intent_management_api_client.api.default import (  # noqa: E402
    create_intent_nfvintent_v1_intents_post,
    delete_intent_nfvintent_v_1_intents_intent_id_delete,
    get_intent_nfvintent_v_1_intents_intent_id_get,
    list_intents_nfvintent_v1_intents_get,
    negotiate_nfvintent_v1_negotiations_post,
    patch_intent_nfvintent_v_1_intents_intent_id_patch,
)
from pragma_intent_management_api_client.models import (  # noqa: E402
    CreateIntentRequest,
    ExpectationTarget,
    ExpectationType,
    FulfilmentInfo,
    FulfilmentStatus,
    IntentExpectation,
    IntentModifications,
    IntentObject,
    NegotiationMode,
    NegotiationRequest,
    NotFulfilledState,
)
from pragma_intent_management_api_client.types import Response  # noqa: E402

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000"


def _intent_object(i: int) -> IntentObject:
    return IntentObject(
        intent_id=f"interop-{i}",
        intent_name="latency-budget",
        intent_expectations=[
            IntentExpectation(
                expectation_id="exp-01",
                expectation_name="latency_ms < 5",
                expectation_type=ExpectationType.PROPERTY,
                expectation_targets=[
                    ExpectationTarget(expectation_target_id="service-01")
                ],
            )
        ],
    )


def _json(content: bytes):
    import json

    return json.loads(content)


def _get(resp, *keys: str):
    """Read a nested value from a generated-client response.

    openapi-python-client drops FastAPI's `-Output` schema variants, so
    create/get/patch responses arrive as raw bytes (parsed=None) or dicts
    rather than typed models. Normalise access across both shapes.
    """
    value = resp.parsed if resp.parsed is not None else _json(resp.content)
    for key in keys:
        value = value[key]
    return value


def main() -> int:
    client = Client(base_url=BASE)

    # 1. create intent through the generated client
    resp: Response = create_intent_nfvintent_v1_intents_post.sync_detailed(
        client=client, body=CreateIntentRequest(intent=_intent_object(1))
    )
    assert resp.status_code == 201, f"create failed: {resp.status_code}"
    intent_id = _get(resp, "intentObjectInstanceId")
    print(f"[1/7] create intent  -> 201, id={intent_id}")

    # 2. list intents
    resp = list_intents_nfvintent_v1_intents_get.sync_detailed(client=client)
    assert resp.status_code == 200
    instances = resp.parsed if isinstance(resp.parsed, list) else _json(resp.content)
    assert any(i.get("intentObjectInstanceId") == intent_id for i in instances)
    print(f"[2/7] list intents   -> 200, {len(instances)} instances")

    # 3. get one intent
    resp = get_intent_nfvintent_v_1_intents_intent_id_get.sync_detailed(
        client=client, intent_id=intent_id
    )
    assert resp.status_code == 200
    assert _get(resp, "intentObjectInstanceId") == intent_id
    print("[3/7] get intent     -> 200")

    # 4. PATCH to COMPLIANT (valid transition ACKNOWLEDGED -> COMPLIANT)
    resp = patch_intent_nfvintent_v_1_intents_intent_id_patch.sync_detailed(
        client=client,
        intent_id=intent_id,
        if_match='"1"',
        body=IntentModifications(
            fulfilment_infos=[
                FulfilmentInfo(
                    fulfilment_object_id="self",
                    fulfilment_status=FulfilmentStatus.NOT_FULFILLED,
                    not_fulfilled_state=NotFulfilledState.COMPLIANT,
                )
            ]
        ),
    )
    assert resp.status_code == 200, f"patch to COMPLIANT failed: {resp.status_code}"
    print("[4/7] PATCH -> COMPLIANT -> 200")

    # 5. PATCH to FULFILLED (COMPLIANT -> FULFILLED)
    resp = patch_intent_nfvintent_v_1_intents_intent_id_patch.sync_detailed(
        client=client,
        intent_id=intent_id,
        if_match='"2"',
        body=IntentModifications(
            fulfilment_infos=[
                FulfilmentInfo(fulfilment_object_id="self", fulfilment_status=FulfilmentStatus.FULFILLED)
            ]
        ),
    )
    assert resp.status_code == 200, f"patch to FULFILLED failed: {resp.status_code}"
    print("[5/7] PATCH -> FULFILLED -> 200")

    # 6. negotiate a pre-creation IntentObject (extension) via the generated client
    resp = negotiate_nfvintent_v1_negotiations_post.sync_detailed(
        client=client,
        body=NegotiationRequest(
            mode=NegotiationMode.SYNC,
            intent_object=_intent_object(2),
        ),
    )
    assert resp.status_code == 200, f"negotiate failed: {resp.status_code}"
    print("[6/7] negotiate      -> 200 (extension)")

    # 7. delete intent
    resp = delete_intent_nfvintent_v_1_intents_intent_id_delete.sync_detailed(
        client=client, intent_id=intent_id
    )
    assert resp.status_code == 204, f"delete failed: {resp.status_code}"
    print("[7/7] delete intent  -> 204")

    print("INTEROP OK — full lifecycle driven through a tool-generated client")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())